/**
 * Writes dist/_headers for Netlify, after `vite build`: security headers, the CSP (which needs the
 * API's origin, so it can't be a fixed string), and cache rules. Netlify is static hosting, so there
 * is no nginx start-up script; everything the browser should know is decided here, at build time.
 *
 *   VITE_API_BASE_URL   the deployed API, e.g. https://skillproof-api.onrender.com/api/v1
 *   CSP_CONNECT_SRC     optional extra connect-src origins, space-separated
 *   CONTEXT             set by Netlify: "production", "deploy-preview" or "branch-deploy"
 *
 * A production build without a real API URL fails, instead of shipping a site that calls localhost.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { buildCsp } from "./csp.mjs";

/** Returns a warning for a missing/local API URL, or throws when this is a production build. */
export function checkApiUrl({ apiBaseUrl, context }) {
  const missing = !apiBaseUrl;
  const local = /^https?:\/\/(localhost|127\.0\.0\.1|\[::1\])(:|\/|$)/.test(apiBaseUrl ?? "");
  if (!missing && !local) return null;
  const message = missing
    ? "VITE_API_BASE_URL is not set, so the site would call http://localhost:8000."
    : `VITE_API_BASE_URL is ${apiBaseUrl}, which only works on your own machine.`;
  const hint =
    " Set it in Netlify (Site configuration -> Environment variables) to https://<api-host>/api/v1.";
  if (context === "production") throw new Error(message + hint);
  return message + hint;
}

export function renderHeaders(csp) {
  return `# Generated by scripts/netlify-headers.mjs at build time. Do not edit.
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: ${csp}

# Hashed build output: cache for a year.
/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Never cache the entry point or the runtime config, so a deploy shows up straight away.
/index.html
  Cache-Control: no-cache
/config.js
  Cache-Control: no-cache
`;
}

function main() {
  const {
    VITE_API_BASE_URL: apiBaseUrl = "",
    CSP_CONNECT_SRC: extraConnectSrc = "",
    CONTEXT: context,
  } = process.env;
  const warning = checkApiUrl({ apiBaseUrl, context });
  if (warning) console.warn(`netlify-headers: warning: ${warning}`);
  const csp = buildCsp({ apiBaseUrl, extraConnectSrc });
  const out = resolve(dirname(fileURLToPath(import.meta.url)), "..", process.argv[2] ?? "dist", "_headers");
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, renderHeaders(csp));
  console.log(`netlify-headers: wrote ${out}`);
  console.log(`netlify-headers: connect-src allows ${csp.match(/connect-src ([^;]*)/)?.[1]}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(`netlify-headers: ${error.message}`);
    process.exit(1);
  }
}
